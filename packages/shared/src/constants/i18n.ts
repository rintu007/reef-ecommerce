export type TranslateFn = (key: string, ...args: number[]) => string;

export function getT(lang?: string): TranslateFn {
  const t = translations[lang || "en"] || translations.en;
  return (key: string, ...args: number[]) => {
    const val = t[key] ?? translations.en[key] ?? key;
    return typeof val === "function" ? val(args[0]) : val;
  };
}

/** Stable translator function, memoized on `lang`. */
export function useT(lang?: string): TranslateFn {
  return useMemo(() => getT(lang || "en"), [lang]);
}
